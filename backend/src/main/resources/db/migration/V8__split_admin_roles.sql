ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check;

ALTER TABLE users
ADD CONSTRAINT users_role_check
CHECK (role IN ('PURCHASING', 'PURCHASING_ADMIN', 'LOGISTICS_OFFICE', 'LOGISTICS_ADMIN', 'DRIVER', 'ADMIN'));

UPDATE users
SET role = 'PURCHASING_ADMIN'
WHERE role = 'ADMIN'
  AND is_super_admin = FALSE;
